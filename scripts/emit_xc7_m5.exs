# Elaborate the two-engine machine for the Zynq-7020 timing harness.
#
#   mix run scripts/emit_xc7_m5.exs
#
# Writes _emit/xc7/xc7_m5_top.v (module `xc7_m5_top`).

File.mkdir_p!("_emit/xc7")

v = PicoBEAM.RTL.Xc7M5Top |> Hw.Compile.Elaborate.elaborate() |> Hw.emit()
File.write!("_emit/xc7/xc7_m5_top.v", v)
mods = Regex.scan(~r/^module\s+(\w+)/m, v) |> Enum.map(fn [_, m] -> m end)
IO.puts("xc7_m5_top: modules=#{Enum.join(mods, ",")} bytes=#{byte_size(v)}")
# Simulation only: every inferred memory zeroed at time 0, which is what
# the bitstream's BRAM and LUTRAM init gives on silicon. Without it
# iverilog reads X out of memory the engines touch before writing, and
# the signature goes X with it. `tb_xc7_m5` includes this.
mems =
  Regex.scan(~r/^\s*reg \[(\d+):0\] (\w+) \[0:(\d+)\];/m, v)
  |> Enum.map(fn [_, _w, name, hi] -> {name, String.to_integer(hi)} end)

init =
  ["// generated by scripts/emit_xc7_m5.exs: zero every memory, as silicon does\n",
   "integer meminit_k;\n", "initial begin\n"] ++
    Enum.map(mems, fn {name, hi} ->
      "  for (meminit_k = 0; meminit_k <= #{hi}; meminit_k = meminit_k + 1) dut.#{name}[meminit_k] = 0;\n"
    end) ++ ["end\n"]

File.write!("_emit/xc7/xc7_m5_meminit.vh", init)
IO.puts("meminit: #{length(mems)} memories")
IO.puts("__XC7_EMIT_DONE__")
