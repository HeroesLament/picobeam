#!/usr/bin/env bash
# Generate an X-origin probe for the post-synthesis netlist.
# Every pb_clk edge it counts primitives whose outputs carry X, per
# class, and names the first few instances of each class to go X.
set -euo pipefail

netlist=${1:-_emit/xc7/nocarry/xc7_m5_synth.v}
out=${2:-_emit/xc7/xprobe.vh}

awk '
  BEGIN {
    outs["FDRE"] = "Q"
    outs["RAMB18E1"] = "DOADO,DOBDO,DOPADOP,DOPBDOP"
    outs["RAMB36E1"] = "DOADO,DOBDO,DOPADOP,DOPBDOP"
    outs["DSP48E1"] = "P"
    outs["RAM32M"] = "DOA,DOB,DOC,DOD"
    outs["RAM64M"] = "DOA,DOB,DOC,DOD"
    outs["MUXF7"] = "O"
    outs["MUXF8"] = "O"
    ncls = split("FDRE RAMB18E1 RAMB36E1 DSP48E1 RAM32M RAM64M MUXF7 MUXF8", cls, " ")
    cur = ""
  }
  # a cell header: "  TYPE #(" or "  TYPE name ("
  /^  [A-Z][A-Z0-9_]* / {
    split($0, f, " ")
    cur = (f[1] in outs) ? f[1] : ""
    if (cur != "" && f[2] != "#(") { insts[cur] = insts[cur] " " f[2]; cur = "" }
    next
  }
  # the end of a parameter list: "  ) name (", or "  ) \esc.name  ("
  /^  \) [^ ]+ +\($/ {
    if (cur != "") { insts[cur] = insts[cur] " " $2 }
    cur = ""
  }
  END {
    print "// generated by scripts/gen_xprobe.sh"
    for (c = 1; c <= ncls; c++) {
      k = cls[c]
      print "integer xp_n_" k " = 0, xp_p_" k " = 0, xp_s_" k " = 0;"
    }
    print "integer xp_stop = 0;"
    print "always @(posedge tb.pb_src) begin"
    for (c = 1; c <= ncls; c++) {
      k = cls[c]
      print "  xp_n_" k " = 0;"
      n = split(insts[k], names, " ")
      for (i = 1; i <= n; i++) {
        # an escaped identifier ends at whitespace; double its backslash in strings
        ref = names[i]; shown = names[i]
        if (substr(ref, 1, 1) == "\\") { ref = ref " "; shown = "\\\\" substr(shown, 2) }
        np = split(outs[k], ps, ",")
        expr = ""
        for (j = 1; j <= np; j++) expr = expr (j > 1 ? ", " : "") "tb.dut." ref "." ps[j]
        printf "  if (^{%s} === 1'"'"'bx) begin xp_n_%s = xp_n_%s + 1; if (xp_s_%s < 6) begin xp_s_%s = xp_s_%s + 1; $display(\"XP first %s %s t=%%0t\", $time); end end\n", expr, k, k, k, k, k, k, shown
      }
      # only name instances on the first sample a class goes X
      print "  if (xp_n_" k " > 0 && xp_s_" k " < 6) xp_s_" k " = 6;"
    }
    printf "  if ("
    for (c = 1; c <= ncls; c++) { k = cls[c]; printf "%sxp_n_%s != xp_p_%s", (c > 1 ? " || " : ""), k, k }
    print ")"
    printf "    $display(\"XP t=%%0t"
    for (c = 1; c <= ncls; c++) printf " %s=%%0d", cls[c]
    printf "\", $time"
    for (c = 1; c <= ncls; c++) printf ", xp_n_%s", cls[c]
    print ");"
    for (c = 1; c <= ncls; c++) { k = cls[c]; print "  xp_p_" k " = xp_n_" k ";" }
    print "  if (xp_n_FDRE > 2000) xp_stop = xp_stop + 1;"
    print "  if (xp_stop > 20) begin $display(\"__XP_DONE__\"); $finish; end"
    print "end"
  }
' "$netlist" > "$out"

wc -l "$out"
grep -c 'XP first' "$out"
